"""## 3. Modelo A - Consumo general

Variables: litros por persona, ratio frente al promedio de los 7 días anteriores del hogar, cambio frente a ayer y fin de semana.
El promedio de 7 días no incluye el día evaluado, así que no hay fuga de datos.
"""

def features_general(g):
    d = g.copy()
    d["ratio_vs_promedio"] = (d["litros_consumidos"] / d["promedio_7_dias"]).fillna(1.0)
    d["sin_historial"] = d["promedio_7_dias"].isna().astype(int)   # primera semana del hogar
    d["cambio_vs_dia_anterior_pct"] = d["cambio_vs_dia_anterior_pct"].fillna(0.0)
    d["fin_de_semana"] = d["fecha"].dt.dayofweek.isin([5, 6]).astype(int)
    return d

COLS_A = ["litros_por_persona", "ratio_vs_promedio", "cambio_vs_dia_anterior_pct", "fin_de_semana"]
dg = features_general(g)

def nuevo_modelo():
    return IsolationForest(n_estimators=300, contamination=CONTAMINACION, random_state=SEMILLA, n_jobs=-1)

# Evaluación entrenar con el pasado (hasta el 10-mar) y probar con el futuro
corte = pd.Timestamp("2026-03-11")
tr, te = dg[dg.fecha < corte], dg[dg.fecha >= corte]
m_eval = nuevo_modelo().fit(tr[COLS_A])
puntaje = -m_eval.decision_function(te[COLS_A])
pred = (m_eval.predict(te[COLS_A]) == -1).astype(int)
y = te["es_anomalia_sintetica"]
print(f"ROC-AUC:   {roc_auc_score(y, puntaje):.3f}")
print(f"Precisión: {precision_score(y, pred):.3f}")
print(f"Recall:    {recall_score(y, pred):.3f}")
print("Matriz de confusión (filas=real, cols=predicho):\n", confusion_matrix(y, pred))

# Modelo final A: entrenado con todos los datos
modelo_a = nuevo_modelo().fit(dg[COLS_A])
dg["puntaje_anomalia"] = -modelo_a.decision_function(dg[COLS_A])
dg["es_anomalia_predicha"] = (modelo_a.predict(dg[COLS_A]) == -1).astype(int)

