"""## 4. Modelo B - Consumo por actividad

Una fila por hogar-día con los litros por persona de cada actividad. Con solo 1000 hogar-días se usa validación cruzada de 5 folds.
"""

CATEGORIAS = ["aseo_personal", "cocina", "inodoro", "lavado_ropa", "limpieza_vivienda"]

def features_actividades(a):
    p = a.pivot_table(index=["hogar_id", "fecha", "personas"], columns="categoria", values="litros_por_persona").reset_index()
    p["total_lpp"] = p[CATEGORIAS].sum(axis=1)
    p["fin_de_semana"] = p["fecha"].dt.dayofweek.isin([5, 6]).astype(int)
    y = a.groupby(["hogar_id", "fecha"])["es_anomalia_sintetica"].max().rename("es_anomalia").reset_index()
    return p.merge(y, on=["hogar_id", "fecha"])

COLS_B = CATEGORIAS + ["total_lpp", "fin_de_semana"]
db = features_actividades(a)

filas = []
for tr_i, te_i in StratifiedKFold(5, shuffle=True, random_state=SEMILLA).split(db[COLS_B], db["es_anomalia"]):
    m = nuevo_modelo().fit(db.iloc[tr_i][COLS_B])
    yt = db.iloc[te_i]["es_anomalia"]
    pr = (m.predict(db.iloc[te_i][COLS_B]) == -1).astype(int)
    filas.append([roc_auc_score(yt, -m.decision_function(db.iloc[te_i][COLS_B])),
                  precision_score(yt, pr, zero_division=0), recall_score(yt, pr)])
print(pd.DataFrame(filas, columns=["ROC-AUC", "Precisión", "Recall"]).mean().round(3))

modelo_b = nuevo_modelo().fit(db[COLS_B])
db["puntaje_anomalia"] = -modelo_b.decision_function(db[COLS_B])
db["es_anomalia_predicha"] = (modelo_b.predict(db[COLS_B]) == -1).astype(int)

"""## 5. Alertas y recomendaciones

Isolation Forest detecta el día raro; las recomendaciones salen de reglas y textos definidos por CONSEJOS.
"""

CONSEJOS = {
    "aseo_personal": "Baños más cortos, cierra la llave al enjabonarte y al cepillarte los dientes. Revisa que la ducha no gotee.",
    "cocina": "Lava los platos con la llave cerrada mientras enjabonas, descongela sin agua corriente y reutiliza el agua de lavar verduras para las plantas.",
    "inodoro": "Un consumo alto aquí suele ser una FUGA en el tanque. Echa colorante en el tanque: si aparece en la taza sin descargar, hay fuga.",
    "lavado_ropa": "Lava solo con carga completa y usa el ciclo de ahorro de agua.",
    "limpieza_vivienda": "Usa balde en vez de manguera para pisos, patios y lavado del carro.",
    "general": "Revisa llaves, tanques y mangueras en busca de fugas y verifica si hubo visitas o actividades fuera de lo normal en casa.",
}

def alerta_general(f):
    txt = f"OJO: el {f['fecha']:%d/%m} usaste {f['litros_consumidos']:.0f} litros"
    if f["personas"] > 1:
        txt += f" ({f['litros_por_persona']:.0f} L por persona)"
    txt += ". "
    if f["sin_historial"] == 0:
        txt += f"Tu promedio de la semana anterior era {f['promedio_7_dias']:.0f} L, o sea {100*(f['ratio_vs_promedio']-1):+.0f} %. "
    return txt, CONSEJOS["general"]

def alerta_actividades(f, base):
    z = {}
    for c in CATEGORIAS:
        med = base[c].median()
        mad = (base[c] - med).abs().median() * 1.4826 or 1e-9
        z[c] = (f[c] - med) / mad
    peor = max(z, key=z.get)
    txt = (f"OJO: el {f['fecha']:%d/%m} el mayor exceso estuvo en {peor.replace('_', ' ')}: "
           f"{f[peor]:.0f} L por persona, cuando lo típico es {base[peor].median():.0f} L.")
    return txt, CONSEJOS[peor]

print("----------Modelo A---------")
for _, f in dg[dg.es_anomalia_predicha == 1].sort_values("puntaje_anomalia", ascending=False).head(3).iterrows():
    t, r = alerta_general(f); print(f"[{f.hogar_id}] {t}\n   → {r}\n")

print("-------Modelo B-------")
for _, f in db[db.es_anomalia_predicha == 1].sort_values("puntaje_anomalia", ascending=False).head(3).iterrows():
    t, r = alerta_actividades(f, db); print(f"[{f.hogar_id}] {t}\n   → {r}\n")

"""## 6. Estadísticas semanales por hogar"""

def estadisticas_semanales(g, hogar_id):
    x = g[g.hogar_id == hogar_id].sort_values("fecha")
    fin = x["fecha"].max()
    sem = x[x.fecha > fin - pd.Timedelta(days=7)]
    ant = x[(x.fecha <= fin - pd.Timedelta(days=7)) & (x.fecha > fin - pd.Timedelta(days=14))]
    personas = int(x["personas"].iloc[0])
    pares = g[(g.personas == personas) & (g.hogar_id != hogar_id) & (g.fecha > fin - pd.Timedelta(days=7))]
    out = {
        "hogar": hogar_id, "personas": personas,
        "litros_semana": round(sem.litros_consumidos.sum()),
        "litros_por_persona_dia": float(round(sem.litros_por_persona.mean(), 1)),
        "dia_de_mayor_consumo": sem.loc[sem.litros_consumidos.idxmax(), "fecha"].strftime("%d/%m"),
    }
    if len(ant):
        out["cambio_vs_semana_anterior_pct"] = float(round(100 * (sem.litros_consumidos.sum() / ant.litros_consumidos.sum() - 1), 1))
    if len(pares):
        out["promedio_hogares_similares_L_pp"] = float(round(pares.litros_por_persona.mean(), 1))
    return out

estadisticas_semanales(g, "H001")

